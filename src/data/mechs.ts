export interface MechHardpoints {
  hd: string;
  ct: string;
  lt: string;
  rt: string;
  la: string;
  ra: string;
  ll: string;
  rl: string;
}

export type MechLocationKey = 'hd' | 'ct' | 'lt' | 'rt' | 'la' | 'ra' | 'll' | 'rl';

/**
 * Built-in equipment that ships with the chassis and cannot be removed.
 * Sourced from the chassis JSON `FixedEquipment` list. Its tonnage and slots
 * are not part of initialTonnage, so the builder reserves them separately.
 * Fixed items are upgrades or jump jets, never weapons, so they do not use
 * hardpoints.
 */
export interface FixedEquipmentItem {
  id: string;              // game ComponentDefID
  name: string;
  location: MechLocationKey;
  tonnage: number;
  slots: number;
  effect: string;
  isJumpJet?: boolean;     // counts toward jumpJetsMax
}

export interface Mech {
  id: number;
  name: string;
  variant: string;
  chassisClass: 'Light' | 'Medium' | 'Heavy' | 'Assault';
  tonnage: number;
  initialTonnage: number;  // fixed chassis weight (engine + structure + gyro) — not available for loadout
  maxArmor: number;
  topSpeed?: number;       // km/h as stored in game
  jumpJetsMax: number;
  hardpoints: MechHardpoints;
  isClan: boolean;
  isLosTech: boolean;
  dlcSource: 'Base' | 'Flashpoint' | 'Urban Warfare' | 'Heavy Metal';
  loreDescription: string | null;
  baseHeatDissipation: number;

  inventorySlots: {
    hd: number; ct: number; lt: number; rt: number;
    la: number; ra: number; ll: number; rl: number;
  };

  fixedEquipment?: FixedEquipmentItem[];
}

